// Difficulty report for World 1 → docs/levels-w1.md.
//   dart compile exe tool/level_report.dart -o build/level_report.exe; ./build/level_report.exe
// Per level:
//   forgiveness — the recorded solution replayed with human-ish sloppiness
//                 (timing ±20 ticks, angles ±4°); share of runs that still win.
//   shake       — random tilting + random valve/fan taps (3 bots); wins / 3★ wins.
//                 A level that shaking wins at 3★ isn't really a puzzle.
import 'dart:io';
import 'dart:math' as math;

import 'package:pour_sand_game/level/level.dart';
import 'package:pour_sand_game/level/level_check.dart';
import 'package:pour_sand_game/level/level_run.dart';

const sloppyRuns = 16, shakeBots = 3;

void main() {
  final paths = parseLevelIndex(File('assets/levels/levels.json').readAsStringSync());
  final rows = <String>[];
  for (final (i, p) in paths.indexed) {
    final level = Level.fromJson(File('assets/levels/$p.json').readAsStringSync());
    final sol = Replay.fromJson(File('assets/levels/$p.replay.json').readAsStringSync());
    final best = LevelRun.play(level, sol);
    final rng = math.Random(i + 1);

    var wins = 0;
    for (var k = 0; k < sloppyRuns; k++) {
      final events = [
        for (final e in sol.events)
          [
            math.max(0, e[0] + rng.nextInt(41) - 20),
            e[1],
            e[1] == 0 && e[2] != 0 ? e[2] + rng.nextInt(17) - 8 : e[2], // ±4° in half-degrees
          ],
      ]..sort((a, b) => a[0].compareTo(b[0]));
      if (LevelRun.play(level, Replay(level.id, events, sol.ticks)).status == RunStatus.won) wins++;
    }

    var shakeWins = 0, shake3 = 0;
    for (var b = 0; b < shakeBots; b++) {
      final events = <List<int>>[];
      for (var t = 0; t < 1500; t += 30) {
        events.add([t, 0, (rng.nextDouble() * 120 - 60).round() * 2]);
        if (rng.nextInt(2) == 0 && level.valves.isNotEmpty) events.add([t, 1, rng.nextInt(level.valves.length)]);
        if (rng.nextInt(3) == 0 && level.fans.isNotEmpty) events.add([t, 3, rng.nextInt(level.fans.length)]);
      }
      final r = LevelRun.play(level, Replay(level.id, events, 1500), extraTicks: 0);
      if (r.status == RunStatus.won) {
        shakeWins++;
        if (r.stars == 3) shake3++;
      }
    }

    final n = i + 1;
    final kind = n % 10 == 0 ? 'boss' : (n % 10 == 9 ? 'breather' : '');
    rows.add('| $n | ${level.name} | $kind | ${level.concept ?? ''} | ${best.stars}★ | '
        '${(best.tick / 60).toStringAsFixed(1)} s | ${(wins * 100 / sloppyRuns).round()}% | $shakeWins/$shakeBots ($shake3 at 3★) |');
    stdout.writeln(rows.last);
  }
  File('docs/levels-w1.md')
    ..createSync(recursive: true)
    ..writeAsStringSync('''# World 1 — level report

Generated by `tool/level_report.dart` from the levels and their recorded solutions
(`tool/build_levels.dart` is the level source). Re-run after changing levels.

- **Solution**: stars and time of the recorded solution (a skilled, exact play).
- **Forgiveness**: the solution replayed $sloppyRuns times with human-ish sloppiness
  (timing ±20 ticks, angles ±4°); share that still win. Low = demanding precision.
- **Shake**: $shakeBots bots tilting randomly (and tapping valves/fans) for 25 s. A level
  winnable at 3★ by shaking is a weak puzzle; acceptable only for tutorials/breathers.

Design targets (GDD §8): first-try fail rate L1–10 < 5%, L11–30 ≈ 15%, late bosses 30–40%.
Forgiveness is the closest headless proxy; real numbers come from playtests (TODO.md).

| # | Level | Kind | Concept | Solution | Time | Forgiveness | Shake |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}
''');
  stdout.writeln('wrote docs/levels-w1.md');
}
